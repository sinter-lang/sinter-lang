//! The compiled simulator behind `sinter sim` (DESIGN §7.2): the generated
//! Rust crate (`rust_sim.rs`), built by cargo as a native runner and streamed.
//!
//! [`build`] writes the module's crate into a cargo workspace of its own in a
//! directory, leaving unchanged files untouched so cargo's rebuild is a no-op
//! when the design hasn't changed, and builds its runner binary in release
//! mode. [`run`] replays a stimulus (and reset schedule) through that binary
//! and hands each step to a callback as it arrives, so a long run never holds
//! its whole trace in memory. The steps are the interpreter's
//! ([`crate::sim::Simulator`]): the conformance oracle checks that the
//! generated crate agrees with it.

use std::ffi::OsString;
use std::io::{BufReader, Read};
use std::path::{Path, PathBuf};
use std::process::{Child, Command, Stdio};

use crate::ir::Module;
use crate::rust_sim;
use crate::sim::{resets_to_bytes, stimulus_to_bytes, AssertFailure};

/// A compiled simulation that couldn't run.
#[derive(Debug, thiserror::Error)]
pub enum NativeError {
    /// A file couldn't be written or read.
    #[error("{action} `{}`: {source}", path.display())]
    Io {
        /// What was being done.
        action: &'static str,
        /// The file.
        path: PathBuf,
        /// The cause.
        source: std::io::Error,
    },
    /// `cargo` couldn't be started.
    #[error("can't run `cargo` (is a Rust toolchain installed?): {0}")]
    NoCargo(std::io::Error),
    /// cargo failed to build the simulator, or the runner failed.
    #[error("{what} failed ({status}):\n{log}")]
    Tool {
        /// Which step.
        what: String,
        /// Its exit status.
        status: String,
        /// The end of its output.
        log: String,
    },
    /// The runner's output stream ended early or was malformed.
    #[error("reading the simulator's output: {0}")]
    Stream(std::io::Error),
    /// The step callback failed.
    #[error("{0}")]
    Step(std::io::Error),
}

/// One step of a compiled run, as [`run`] hands it to its callback.
#[derive(Debug, Clone, Copy)]
pub struct Step<'a> {
    /// The 0-based step index.
    pub index: usize,
    /// The edge time (the cycle, with one clock).
    pub time: u64,
    /// Which clock domains had an edge, by index into the module's domains.
    pub ticking: &'a [bool],
    /// The outputs sampled this step, in port order.
    pub outputs: &'a [u64],
    /// With `probe`: the held inputs, the registers before the edge, then
    /// every wire, in the module's order ([`rust_sim::probe_len`] words).
    /// Empty otherwise.
    pub probe: &'a [u64],
}

/// The cargo to run: the one running this process, if any, else `cargo`.
fn cargo() -> OsString {
    std::env::var_os("CARGO").unwrap_or_else(|| "cargo".into())
}

/// Whether `cargo` runs.
#[must_use]
pub fn cargo_available() -> bool {
    Command::new(cargo())
        .arg("--version")
        .output()
        .is_ok_and(|o| o.status.success())
}

/// Write `module`'s simulator crate into `dir` (a cargo workspace of its own,
/// so it builds even inside another project's workspace) and build its
/// runner in release mode, with the `probe` feature when `probe`. Returns the
/// runner executable.
///
/// Files are only rewritten when their contents change, so rebuilding an
/// unchanged design costs cargo's up-to-date check alone.
///
/// # Errors
/// A [`NativeError`] if a file can't be written, cargo is missing, or the
/// build fails.
pub fn build(dir: &Path, module: &Module, probe: bool) -> Result<PathBuf, NativeError> {
    let krate = rust_sim::crate_name(module);
    write_if_changed(
        &dir.join("Cargo.toml"),
        &format!(
            "# Generated by sinter: the workspace `sinter sim` builds `{krate}` in.\n\
             [workspace]\n\
             resolver = \"2\"\n\
             members = [\"{krate}\"]\n\
             \n\
             [profile.release]\n\
             debug = false\n\
             incremental = false\n"
        ),
    )?;
    for (rel, contents) in rust_sim::emit_crate(module, &krate) {
        write_if_changed(&dir.join(&krate).join(rel), &contents)?;
    }
    let target = dir.join("target");
    let mut cmd = Command::new(cargo());
    cmd.args(["build", "--release", "--quiet", "--manifest-path"])
        .arg(dir.join(&krate).join("Cargo.toml"))
        .arg("--target-dir")
        .arg(&target);
    if probe {
        cmd.args(["--features", "probe"]);
    }
    let out = cmd.output().map_err(NativeError::NoCargo)?;
    if !out.status.success() {
        return Err(tool_error(
            format!("building the simulator of `{}`", module.name),
            out.status.to_string(),
            &out.stdout,
            &out.stderr,
        ));
    }
    Ok(target
        .join("release")
        .join(format!("{krate}{}", std::env::consts::EXE_SUFFIX)))
}

/// Run the runner `exe` (from [`build`]) over `stimulus`, with `rst_n`
/// asserted in each step `k` where `resets[k]`, calling `on_step` with each
/// step as it arrives. With `probe` (the runner must have been built with
/// it) each step also carries its signals. `dir` holds the stimulus files.
/// Returns the `assert!` failures, in step order.
///
/// # Errors
/// A [`NativeError`] if a file can't be written, the runner fails or its
/// output is malformed, or `on_step` fails (which stops the run).
pub fn run(
    exe: &Path,
    dir: &Path,
    module: &Module,
    stimulus: &[Vec<u64>],
    resets: &[bool],
    probe: bool,
    mut on_step: impl FnMut(&Step) -> std::io::Result<()>,
) -> Result<Vec<AssertFailure>, NativeError> {
    let stim = dir.join("stimulus.bin");
    write_bytes(&stim, &stimulus_to_bytes(stimulus))?;
    let mut cmd = Command::new(exe);
    cmd.arg(&stim).arg(stimulus.len().to_string());
    if !resets.is_empty() {
        let path = dir.join("resets.bin");
        write_bytes(&path, &resets_to_bytes(resets))?;
        cmd.arg("--resets").arg(path);
    }
    if probe {
        cmd.arg("--probe");
    }
    let mut child = cmd
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .spawn()
        .map_err(|source| NativeError::Io {
            action: "running",
            path: exe.to_path_buf(),
            source,
        })?;
    let read = child
        .stdout
        .take()
        .map(|out| read_steps(out, module, stimulus.len(), probe, &mut on_step));
    let result = match read {
        Some(Ok(failures)) => Ok(failures),
        Some(Err(e)) => Err(e),
        None => Err(NativeError::Stream(std::io::Error::other("no stdout"))),
    };
    finish(child, exe, result)
}

/// Wait for the runner. A runner that failed reports its own error (the
/// stream it left is incomplete); one stopped early by `on_step` is killed.
fn finish<T>(
    mut child: Child,
    exe: &Path,
    result: Result<T, NativeError>,
) -> Result<T, NativeError> {
    if result.is_err() {
        let _ = child.kill();
    }
    let mut stderr = Vec::new();
    if let Some(mut err) = child.stderr.take() {
        let _ = err.read_to_end(&mut stderr);
    }
    let status = child.wait().map_err(|source| NativeError::Io {
        action: "waiting for",
        path: exe.to_path_buf(),
        source,
    })?;
    match result {
        Err(NativeError::Step(e)) => Err(NativeError::Step(e)),
        _ if !status.success() => Err(tool_error(
            "the compiled simulator".to_string(),
            status.to_string(),
            &[],
            &stderr,
        )),
        r => r,
    }
}

/// Read `cycles` steps, then the assert failures, from the runner's stdout.
fn read_steps(
    out: impl Read,
    module: &Module,
    cycles: usize,
    probe: bool,
    on_step: &mut impl FnMut(&Step) -> std::io::Result<()>,
) -> Result<Vec<AssertFailure>, NativeError> {
    let mut r = BufReader::with_capacity(1 << 16, out);
    let nd = module.domains.len().max(1);
    let no = module.outputs().count();
    let np = if probe {
        rust_sim::probe_len(module)
    } else {
        0
    };
    let mut words = vec![0u64; 1 + nd + no + np];
    let mut bytes = vec![0u8; words.len() * 8];
    let mut ticking = vec![false; nd];
    for index in 0..cycles {
        r.read_exact(&mut bytes).map_err(NativeError::Stream)?;
        for (w, b) in words.iter_mut().zip(bytes.chunks_exact(8)) {
            *w = le_word(b);
        }
        for (t, &w) in ticking.iter_mut().zip(&words[1..=nd]) {
            *t = w != 0;
        }
        on_step(&Step {
            index,
            time: words[0],
            ticking: &ticking,
            outputs: &words[1 + nd..1 + nd + no],
            probe: &words[1 + nd + no..],
        })
        .map_err(NativeError::Step)?;
    }
    let count = read_word(&mut r)?;
    let mut failures = Vec::new();
    for _ in 0..count {
        let cycle = usize::try_from(read_word(&mut r)?).unwrap_or(usize::MAX);
        let msg = read_str(&mut r)?;
        let loc = read_str(&mut r)?;
        failures.push(AssertFailure { cycle, msg, loc });
    }
    Ok(failures)
}

fn le_word(b: &[u8]) -> u64 {
    let mut w = [0u8; 8];
    w.copy_from_slice(b);
    u64::from_le_bytes(w)
}

fn read_word(r: &mut impl Read) -> Result<u64, NativeError> {
    let mut b = [0u8; 8];
    r.read_exact(&mut b).map_err(NativeError::Stream)?;
    Ok(u64::from_le_bytes(b))
}

fn read_str(r: &mut impl Read) -> Result<String, NativeError> {
    let len = usize::try_from(read_word(r)?).unwrap_or(usize::MAX);
    // A message is short; a huge length means a corrupt stream.
    if len > 1 << 20 {
        return Err(NativeError::Stream(std::io::Error::other(
            "an assert message is implausibly long",
        )));
    }
    let mut b = vec![0u8; len];
    r.read_exact(&mut b).map_err(NativeError::Stream)?;
    Ok(String::from_utf8_lossy(&b).into_owned())
}

fn tool_error(what: String, status: String, stdout: &[u8], stderr: &[u8]) -> NativeError {
    let log = format!(
        "{}{}",
        String::from_utf8_lossy(stdout),
        String::from_utf8_lossy(stderr)
    );
    // The error comes last, after any warnings.
    let lines: Vec<&str> = log.lines().collect();
    NativeError::Tool {
        what,
        status,
        log: lines[lines.len().saturating_sub(40)..].join("\n"),
    }
}

/// Write `contents` to `path` unless it already holds exactly that, so cargo
/// doesn't rebuild an unchanged crate.
fn write_if_changed(path: &Path, contents: &str) -> Result<(), NativeError> {
    if std::fs::read(path).is_ok_and(|old| old == contents.as_bytes()) {
        return Ok(());
    }
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent).map_err(|source| NativeError::Io {
            action: "creating",
            path: parent.to_path_buf(),
            source,
        })?;
    }
    write_bytes(path, contents.as_bytes())
}

fn write_bytes(path: &Path, bytes: &[u8]) -> Result<(), NativeError> {
    std::fs::write(path, bytes).map_err(|source| NativeError::Io {
        action: "writing",
        path: path.to_path_buf(),
        source,
    })
}
