//! The generated Rust simulator (DESIGN §7.2): `sinter build --emit rust`.
//!
//! Emits a standalone, dependency-free crate that models one [`Module`]
//! cycle for cycle, for Rust testbenches. Its `step` is straight-line code
//! that follows [`crate::sim::Simulator::step`] exactly: advance to the next
//! clock edge, take the ticking domains' inputs, evaluate the wires in order,
//! check the asserts, sample the outputs, then commit the ticking domains'
//! registers and memory ports. The arithmetic is `sim_runtime.rs`,
//! copied into the crate as `src/runtime.rs`, so the two simulators share it.

use std::collections::HashMap;
use std::fmt::Write as _;

use sinter_syntax::ast::{CastMode, Type};

use crate::eval::{rt_bin, rt_un};
use crate::ir::{Expr, ExprKind, Module, Port};

/// The runtime every generated crate carries.
const RUNTIME: &str = include_str!("sim_runtime.rs");

/// The default crate name for `module`'s simulator: its name in snake case,
/// plus `-sim` (`AsyncFifo` gives `async_fifo-sim`).
#[must_use]
pub fn crate_name(module: &Module) -> String {
    let mut out = String::new();
    for (i, c) in module.name.chars().enumerate() {
        if c.is_ascii_uppercase() {
            if i > 0 && !out.ends_with('_') {
                out.push('_');
            }
            out.push(c.to_ascii_lowercase());
        } else {
            out.push(c);
        }
    }
    out + "-sim"
}

/// The name of the struct holding `module`'s state in its simulator crate: the
/// module's own name, unless that would clash with the crate's other types.
#[must_use]
pub fn model_name(module: &Module) -> &str {
    match module.name.as_str() {
        "Inputs" | "Outputs" | "AssertFailure" => "Sim",
        n => n,
    }
}

/// The files of `module`'s simulator crate, named `crate_name`: paths relative
/// to the crate root, with their contents.
#[must_use]
pub fn emit_crate(module: &Module, crate_name: &str) -> Vec<(&'static str, String)> {
    vec![
        ("Cargo.toml", cargo_toml(module, crate_name)),
        ("src/lib.rs", Gen::new(module).lib(crate_name)),
        ("src/runtime.rs", RUNTIME.to_string()),
    ]
}

fn cargo_toml(module: &Module, crate_name: &str) -> String {
    format!(
        "# Generated by sinter {} from module `{}`. Do not edit.\n\
         [package]\n\
         name = \"{crate_name}\"\n\
         version = \"0.1.0\"\n\
         edition = \"2021\"\n\
         publish = false\n\
         description = \"Cycle-accurate simulator of the Sinter module `{}`.\"\n\
         \n\
         [lib]\n\
         path = \"src/lib.rs\"\n",
        env!("CARGO_PKG_VERSION"),
        module.name,
        module.name
    )
}

/// What an IR name refers to: an input, a register, or a wire (by index).
#[derive(Clone, Copy)]
enum Ref {
    Input(usize),
    Reg(usize),
    Wire(usize),
}

struct Gen<'a> {
    m: &'a Module,
    /// Name resolution, with the interpreter's precedence: inputs, then
    /// registers, then wires.
    refs: HashMap<&'a str, Ref>,
    inputs: Vec<&'a Port>,
    outputs: Vec<&'a Port>,
}

impl<'a> Gen<'a> {
    fn new(m: &'a Module) -> Self {
        let inputs: Vec<&Port> = m.inputs().collect();
        let outputs: Vec<&Port> = m.outputs().collect();
        let mut refs = HashMap::new();
        for (k, p) in inputs.iter().enumerate() {
            refs.entry(p.name.as_str()).or_insert(Ref::Input(k));
        }
        for (k, r) in m.regs.iter().enumerate() {
            refs.entry(r.name.as_str()).or_insert(Ref::Reg(k));
        }
        for (k, l) in m.lets.iter().enumerate() {
            refs.entry(l.name.as_str()).or_insert(Ref::Wire(k));
        }
        Gen {
            m,
            refs,
            inputs,
            outputs,
        }
    }

    fn sim_name(&self) -> &str {
        model_name(self.m)
    }

    fn lib(&self, crate_name: &str) -> String {
        let lib = crate_name.replace('-', "_");
        let sim = self.sim_name();
        let mut s = String::new();
        let _ = writeln!(
            s,
            "//! Cycle-accurate simulator of the Sinter module `{}`, generated by\n\
             //! `sinter build --emit rust` (sinter {}). Do not edit.\n\
             //!\n\
             //! Each [`{sim}::step`] is one clock cycle: it takes that cycle's\n\
             //! [`Inputs`] and returns the [`Outputs`] sampled before the clock edge,\n\
             //! exactly as the emitted Verilog behaves.\n\
             //!\n\
             //! ```ignore\n\
             //! let mut sim = {lib}::{sim}::new();\n\
             //! let out = sim.step(&{lib}::Inputs::default());\n\
             //! ```",
            self.m.name,
            env!("CARGO_PKG_VERSION"),
        );
        s.push_str(
            "\n#![forbid(unsafe_code)]\n\
             // Generated straight-line code: some wires are only read by other\n\
             // generated code paths, and the expressions nest runtime calls.\n\
             #![allow(unused_variables, unused_mut, unused_parens, clippy::all)]\n\
             \n\
             #[allow(dead_code)]\n\
             mod runtime;\n\
             use runtime as rt;\n\n",
        );
        self.ports_struct(&mut s, "Inputs", "One cycle's inputs.", &self.inputs);
        self.ports_struct(
            &mut s,
            "Outputs",
            "The outputs sampled in one cycle.",
            &self.outputs,
        );
        s.push_str(
            "/// A sim-only `assert!` that read false.\n\
             #[derive(Debug, Clone, PartialEq, Eq)]\n\
             pub struct AssertFailure {\n\
             \x20   /// The 0-based step it fired on.\n\
             \x20   pub cycle: u64,\n\
             \x20   /// The assertion's message.\n\
             \x20   pub msg: &'static str,\n\
             \x20   /// Its static backtrace, e.g. `Top -> Inner::guard@16 (line 6)`.\n\
             \x20   pub loc: &'static str,\n\
             }\n\n",
        );
        self.consts(&mut s);
        self.sim_struct(&mut s);
        s
    }

    /// `Inputs` / `Outputs`: one typed field per port, plus raw conversions.
    fn ports_struct(&self, s: &mut String, name: &str, doc: &str, ports: &[&Port]) {
        let n = ports.len();
        let _ = writeln!(
            s,
            "/// {doc}\n#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]\npub struct {name} {{"
        );
        for p in ports {
            let fixed = if p.frac_bits > 0 {
                format!(" (fixed point, {} fractional bits)", p.frac_bits)
            } else {
                String::new()
            };
            let _ = writeln!(
                s,
                "    /// `{}: {}`{fixed}\n    pub {}: {},",
                p.name,
                p.ty,
                field(&p.name),
                rust_ty(p.ty)
            );
        }
        let names = ports
            .iter()
            .map(|p| format!("{:?}", p.name))
            .collect::<Vec<_>>()
            .join(", ");
        let from = ports
            .iter()
            .enumerate()
            .map(|(k, p)| {
                format!(
                    "{}: {}",
                    field(&p.name),
                    from_raw(p.ty, &format!("raw[{k}]"))
                )
            })
            .collect::<Vec<_>>()
            .join(", ");
        let to = ports
            .iter()
            .map(|p| to_raw(p.ty, &format!("self.{}", field(&p.name))))
            .collect::<Vec<_>>()
            .join(", ");
        let _ = writeln!(
            s,
            "}}\n\n\
             impl {name} {{\n\
             \x20   /// The port names, in raw order.\n\
             \x20   pub const NAMES: [&'static str; {n}] = [{names}];\n\n\
             \x20   /// From raw bit patterns, in [`{name}::NAMES`] order.\n\
             \x20   #[must_use]\n\
             \x20   pub fn from_raw(raw: &[u64; {n}]) -> Self {{\n\
             \x20       {name} {{ {from} }}\n\
             \x20   }}\n\n\
             \x20   /// As raw bit patterns (each masked to its port's width).\n\
             \x20   #[must_use]\n\
             \x20   pub fn to_raw(&self) -> [u64; {n}] {{\n\
             \x20       [{to}]\n\
             \x20   }}\n\
             }}\n"
        );
    }

    fn consts(&self, s: &mut String) {
        let m = self.m;
        let periods: Vec<String> = if m.domains.is_empty() {
            vec!["1".into()]
        } else {
            m.domains
                .iter()
                .map(|d| d.period.max(1).to_string())
                .collect()
        };
        let _ = writeln!(
            s,
            "/// Each clock domain's period.\nconst PERIODS: [u64; {}] = [{}];",
            periods.len(),
            periods.join(", ")
        );
        let _ = writeln!(
            s,
            "/// Register names, in state order.\nconst REG_NAMES: [&str; {}] = [{}];",
            m.regs.len(),
            join(m.regs.iter().map(|r| format!("{:?}", r.name)))
        );
        let _ = writeln!(
            s,
            "/// Register reset values.\nconst RESET: [u64; {}] = [{}];",
            m.regs.len(),
            join(m.regs.iter().map(|r| format!("{:#x}", r.reset)))
        );
        let _ = writeln!(
            s,
            "/// Memory names, in state order.\nconst MEM_NAMES: [&str; {}] = [{}];\n",
            m.mems.len(),
            join(m.mems.iter().map(|x| format!("{:?}", x.name)))
        );
        for (k, mem) in m.mems.iter().enumerate() {
            if mem.reset.iter().any(|&v| v != 0) {
                let _ = writeln!(
                    s,
                    "/// `{}`'s initial contents.\nconst MEM{k}_INIT: [u64; {}] = [{}];\n",
                    mem.name,
                    mem.reset.len(),
                    join(mem.reset.iter().map(|v| format!("{v:#x}")))
                );
            }
        }
    }

    fn sim_struct(&self, s: &mut String) {
        let m = self.m;
        let sim = self.sim_name();
        let (ni, nr, nd) = (self.inputs.len(), m.regs.len(), m.domains.len().max(1));
        let mems = join(m.mems.iter().enumerate().map(|(k, mem)| {
            if mem.reset.iter().any(|&v| v != 0) {
                format!("MEM{k}_INIT.to_vec()")
            } else {
                format!("vec![0; {}]", mem.depth)
            }
        }));
        let no = self.outputs.len();
        let _ = write!(
            s,
            "/// The model of `{name}`: its registers, memories, and clocks.\n\
             #[derive(Debug, Clone)]\n\
             pub struct {sim} {{\n\
             \x20   regs: [u64; {nr}],\n\
             \x20   /// Input values, held between a domain's clock edges.\n\
             \x20   held: [u64; {ni}],\n\
             \x20   mems: Vec<Vec<u64>>,\n\
             \x20   cycle: u64,\n\
             \x20   failures: Vec<AssertFailure>,\n\
             \x20   next_edge: [u64; {nd}],\n\
             \x20   time: u64,\n\
             \x20   ticked: [bool; {nd}],\n\
             }}\n\n\
             impl Default for {sim} {{\n\
             \x20   fn default() -> Self {{\n\
             \x20       Self::new()\n\
             \x20   }}\n\
             }}\n\n\
             impl {sim} {{\n\
             \x20   /// A model with every register and memory at its reset value.\n\
             \x20   #[must_use]\n\
             \x20   pub fn new() -> Self {{\n\
             \x20       {sim} {{\n\
             \x20           regs: RESET,\n\
             \x20           held: [0; {ni}],\n\
             \x20           mems: vec![{mems}],\n\
             \x20           cycle: 0,\n\
             \x20           failures: Vec::new(),\n\
             \x20           next_edge: [0; {nd}],\n\
             \x20           time: 0,\n\
             \x20           ticked: [false; {nd}],\n\
             \x20       }}\n\
             \x20   }}\n\n\
             \x20   /// Return to the reset state, clearing recorded assert failures.\n\
             \x20   pub fn reset(&mut self) {{\n\
             \x20       *self = Self::new();\n\
             \x20   }}\n\n\
             \x20   /// The time of the most recent step, in clock-period units.\n\
             \x20   #[must_use]\n\
             \x20   pub fn time(&self) -> u64 {{\n\
             \x20       self.time\n\
             \x20   }}\n\n\
             \x20   /// Which clock domains had an edge in the most recent step.\n\
             \x20   #[must_use]\n\
             \x20   pub fn ticked(&self) -> &[bool] {{\n\
             \x20       &self.ticked\n\
             \x20   }}\n\n\
             \x20   /// The `assert!` failures so far, in step order.\n\
             \x20   #[must_use]\n\
             \x20   pub fn assert_failures(&self) -> &[AssertFailure] {{\n\
             \x20       &self.failures\n\
             \x20   }}\n\n\
             \x20   /// A register's current value, by its flattened name.\n\
             \x20   #[must_use]\n\
             \x20   pub fn register(&self, name: &str) -> Option<u64> {{\n\
             \x20       REG_NAMES.iter().position(|n| *n == name).map(|i| self.regs[i])\n\
             \x20   }}\n\n\
             \x20   /// A memory's current contents, by its flattened name.\n\
             \x20   #[must_use]\n\
             \x20   pub fn memory(&self, name: &str) -> Option<&[u64]> {{\n\
             \x20       MEM_NAMES\n\
             \x20           .iter()\n\
             \x20           .position(|n| *n == name)\n\
             \x20           .map(|i| self.mems[i].as_slice())\n\
             \x20   }}\n\n\
             \x20   /// Run a fresh model over raw input rows (in [`Inputs::NAMES`] order),\n\
             \x20   /// returning the raw output rows (in [`Outputs::NAMES`] order).\n\
             \x20   #[must_use]\n\
             \x20   pub fn run_raw(inputs: &[[u64; {ni}]]) -> Vec<[u64; {no}]> {{\n\
             \x20       let mut sim = Self::new();\n\
             \x20       inputs\n\
             \x20           .iter()\n\
             \x20           .map(|row| sim.step(&Inputs::from_raw(row)).to_raw())\n\
             \x20           .collect()\n\
             \x20   }}\n",
            name = m.name,
        );
        self.step_fn(s);
        s.push_str("}\n");
    }

    fn step_fn(&self, s: &mut String) {
        let m = self.m;
        let nd = m.domains.len().max(1);
        s.push_str(
            "\n    /// Advance to the next clock edge: the domains with an edge take\n\
             \x20   /// their new inputs and commit their next state; the others hold.\n\
             \x20   /// Returns the outputs sampled before the edge.\n\
             \x20   pub fn step(&mut self, inputs: &Inputs) -> Outputs {\n",
        );
        let _ = writeln!(
            s,
            "        let t = self.next_edge.iter().copied().fold(u64::MAX, u64::min);\n\
             \x20       let tick: [bool; {nd}] = core::array::from_fn(|d| self.next_edge[d] == t);\n\
             \x20       for d in 0..{nd} {{\n\
             \x20           if tick[d] {{\n\
             \x20               self.next_edge[d] = t + PERIODS[d];\n\
             \x20           }}\n\
             \x20       }}\n\
             \x20       self.time = t;\n\
             \x20       self.ticked = tick;\n\
             \x20       let raw = inputs.to_raw();"
        );
        for (k, p) in self.inputs.iter().enumerate() {
            let _ = writeln!(
                s,
                "        if tick[{}] {{\n            self.held[{k}] = raw[{k}];\n        }}",
                p.domain
            );
        }
        s.push_str("        let x = &self.held;\n        let r = &self.regs;\n");
        for (k, l) in m.lets.iter().enumerate() {
            let _ = writeln!(s, "        // {}", l.name);
            let _ = writeln!(s, "        let w{k} = {};", self.expr(&l.value));
        }
        for a in &m.asserts {
            let _ = writeln!(
                s,
                "        if tick[{}] && {} == 0 {{\n\
                 \x20           self.failures.push(AssertFailure {{\n\
                 \x20               cycle: self.cycle,\n\
                 \x20               msg: {:?},\n\
                 \x20               loc: {:?},\n\
                 \x20           }});\n\
                 \x20       }}",
                a.domain,
                self.expr(&a.cond),
                a.msg,
                a.loc
            );
        }
        s.push_str("        self.cycle += 1;\n");
        let outs = join(self.outputs.iter().map(|p| {
            m.out_drives
                .iter()
                .find(|(n, _)| *n == p.name)
                .map_or_else(|| "0u64".to_string(), |(_, e)| self.expr(e))
        }));
        let _ = writeln!(
            s,
            "        let out = Outputs::from_raw(&[{outs}]);\n        let mut n = self.regs;"
        );
        let reg_index: HashMap<&str, usize> = m
            .regs
            .iter()
            .enumerate()
            .map(|(i, r)| (r.name.as_str(), i))
            .collect();
        let mem_index: HashMap<&str, usize> = m
            .mems
            .iter()
            .enumerate()
            .map(|(i, x)| (x.name.as_str(), i))
            .collect();
        for (name, e) in &m.reg_updates {
            if let Some(&i) = reg_index.get(name.as_str()) {
                let _ = writeln!(
                    s,
                    "        if tick[{}] {{\n            n[{i}] = {};\n        }}",
                    m.regs[i].domain,
                    self.expr(e)
                );
            }
        }
        // Reads latch the pre-edge contents, so they come before the writes.
        for rd in &m.mem_reads {
            let (Some(&ri), Some(&mi)) = (
                reg_index.get(rd.rdata.as_str()),
                mem_index.get(rd.mem.as_str()),
            ) else {
                continue;
            };
            let _ = writeln!(
                s,
                "        if tick[{}] {{\n\
                 \x20           n[{ri}] = self.mems[{mi}].get(({}) as usize).copied().unwrap_or(0);\n\
                 \x20       }}",
                rd.domain,
                self.expr(&rd.addr)
            );
        }
        for wr in &m.mem_writes {
            let Some(&mi) = mem_index.get(wr.mem.as_str()) else {
                continue;
            };
            let _ = writeln!(
                s,
                "        if tick[{}] {{\n\
                 \x20           let we = {};\n\
                 \x20           if we != 0 {{\n\
                 \x20               let idx = ({}) as usize;\n\
                 \x20               let data = {};\n\
                 \x20               if let Some(cell) = self.mems[{mi}].get_mut(idx) {{\n\
                 \x20                   rt::write_lanes(cell, we, data, {});\n\
                 \x20               }}\n\
                 \x20           }}\n\
                 \x20       }}",
                wr.domain,
                self.expr(&wr.we),
                self.expr(&wr.addr),
                self.expr(&wr.data),
                wr.we.ty.width()
            );
        }
        s.push_str("        self.regs = n;\n        out\n    }\n");
    }

    /// `e` as a Rust `u64` expression.
    fn expr(&self, e: &Expr) -> String {
        let mut out = String::new();
        self.write_expr(e, &mut out);
        out
    }

    fn write_expr(&self, e: &Expr, o: &mut String) {
        match &e.kind {
            ExprKind::Literal(v) => {
                let _ = write!(o, "{v:#x}u64");
            }
            ExprKind::Ident(n) => match self.refs.get(n.as_str()) {
                Some(Ref::Input(k)) => {
                    let _ = write!(o, "x[{k}]");
                }
                Some(Ref::Reg(k)) => {
                    let _ = write!(o, "r[{k}]");
                }
                Some(Ref::Wire(k)) => {
                    let _ = write!(o, "w{k}");
                }
                // The checker keeps every name in scope; the interpreter reads
                // an unknown one as 0.
                None => o.push_str("0u64"),
            },
            ExprKind::Unary { op, expr } => {
                let _ = write!(o, "rt::unary(rt::Un::{:?}, ", rt_un(*op));
                self.write_expr(expr, o);
                let _ = write!(o, ", {})", ty(expr.ty));
            }
            ExprKind::Binary { op, lhs, rhs } => {
                let _ = write!(o, "rt::binary(rt::Bin::{:?}, ", rt_bin(*op));
                self.write_expr(lhs, o);
                let _ = write!(o, ", {}, ", ty(lhs.ty));
                self.write_expr(rhs, o);
                let _ = write!(o, ", {}, {})", ty(rhs.ty), ty(e.ty));
            }
            ExprKind::If { cond, then, els } => {
                o.push_str("(if ");
                self.write_expr(cond, o);
                o.push_str(" != 0 { ");
                self.write_expr(then, o);
                o.push_str(" } else { ");
                self.write_expr(els, o);
                o.push_str(" })");
            }
            ExprKind::Cast { expr, mode } => {
                // `trunc` / `round` lower to shifts before the IR, as in `eval`.
                let f = match mode {
                    CastMode::Sat => "sat",
                    CastMode::Wrap | CastMode::Trunc | CastMode::Round => "wrap",
                };
                let _ = write!(o, "rt::{f}(");
                self.write_expr(expr, o);
                let _ = write!(o, ", {}, {})", ty(expr.ty), ty(e.ty));
            }
            ExprKind::Shl { expr, amount } => {
                o.push_str("rt::shl(");
                self.write_expr(expr, o);
                let _ = write!(o, ", {}, {amount})", e.ty.width());
            }
            ExprKind::Shr { expr, amount } => {
                o.push_str("rt::shr(");
                self.write_expr(expr, o);
                let _ = write!(o, ", {}, {}, {amount})", ty(expr.ty), e.ty.width());
            }
            ExprKind::VarShift { expr, amount, left } => {
                o.push_str("rt::var_shift(");
                self.write_expr(expr, o);
                o.push_str(", ");
                self.write_expr(amount, o);
                let _ = write!(o, ", {}, {left})", ty(expr.ty));
            }
        }
    }
}

/// `ty` as a runtime type constructor.
fn ty(t: Type) -> String {
    match t {
        Type::Uint(w) => format!("rt::u({w})"),
        Type::Int(w) => format!("rt::i({w})"),
    }
}

/// The smallest Rust integer type holding a value of `t`.
fn rust_ty(t: Type) -> &'static str {
    let w = t.width();
    match (t.is_signed(), w) {
        (false, 0..=8) => "u8",
        (false, 9..=16) => "u16",
        (false, 17..=32) => "u32",
        (false, _) => "u64",
        (true, 0..=8) => "i8",
        (true, 9..=16) => "i16",
        (true, 17..=32) => "i32",
        (true, _) => "i64",
    }
}

/// A typed field from raw bits `v`: masked, and sign-extended if signed.
fn from_raw(t: Type, v: &str) -> String {
    let w = t.width();
    let rt = rust_ty(t);
    if t.is_signed() {
        format!("rt::signed_value(rt::mask({v}, {w}), rt::i({w})) as {rt}")
    } else {
        format!("rt::mask({v}, {w}) as {rt}")
    }
}

/// A typed field `v` as raw bits, masked to its port's width.
fn to_raw(t: Type, v: &str) -> String {
    format!("rt::mask({v} as u64, {})", t.width())
}

/// A port name as a Rust field name: a raw identifier if it is a keyword.
fn field(name: &str) -> String {
    const KEYWORDS: &[&str] = &[
        "abstract", "as", "async", "await", "become", "box", "break", "const", "continue", "do",
        "dyn", "else", "enum", "extern", "false", "final", "fn", "for", "gen", "if", "impl", "in",
        "let", "loop", "macro", "match", "mod", "move", "mut", "override", "priv", "pub", "ref",
        "return", "static", "struct", "trait", "true", "try", "type", "typeof", "unsafe",
        "unsized", "use", "virtual", "where", "while", "yield",
    ];
    match name {
        // These can't be raw identifiers.
        "self" | "Self" | "super" | "crate" => format!("{name}_"),
        n if KEYWORDS.contains(&n) => format!("r#{n}"),
        n => n.to_string(),
    }
}

fn join(items: impl Iterator<Item = String>) -> String {
    items.collect::<Vec<_>>().join(", ")
}
